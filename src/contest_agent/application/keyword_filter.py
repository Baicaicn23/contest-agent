"""关键词粗筛：用零成本的关键词匹配，挡掉明显与比赛无关的通知。

为什么要有这一层？——LLM 调用要花钱花时间。官网通知大部分是
名单公示、教学安排这类杂事，如果每条都去问 LLM，成本全冤在垃圾上。
粗筛的取向是"宁滥勿缺"：只要沾到任何一个词就放行去见 LLM，
严格把关交给 LLM（它见过正文，判断得准）；粗筛这边漏掉一个真比赛
才是真正的损失，多放几条垃圾只是多花几分钱。
"""

# 关键词列表刻意收得宽："报名""选拔"这类词也会放进大量非比赛通知，
# 但它们可能藏着没提"竞赛"二字的比赛（如"XX认证报名"），放行是对的
KEYWORDS = (
    "竞赛", "大赛", "比赛", "锦标赛", "争夺赛",
    "认证", "测评", "等级考试",
    "报名", "参赛",
)


def keyword_hit(text: str) -> str | None:
    """在文本里找比赛相关关键词，返回第一个命中的词；没命中返回 None。

    返回命中词本身（而不是布尔值）是为了可解释：
    结果里能写出"因为命中'竞赛'所以去问了 LLM"。
    """
    for keyword in KEYWORDS:
        if keyword in text:
            return keyword
    return None
