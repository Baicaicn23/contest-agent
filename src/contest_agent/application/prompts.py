# 系统提示词：告诉模型它是谁、输出什么格式、按什么标准判断。
# 写提示词的经验：角色 + 输出格式（带字段说明）+ 正反判定标准，三段缺一不可。
# "只输出 JSON"这句必须存在——DeepSeek 开 JSON 模式要求提示词里出现 json 字样，
# 同时也是防模型自由发挥的第一道闸。
IDENTIFY_SYSTEM_PROMPT = """\
你负责判断高校学院官网的通知是不是"学生比赛类通知"，并提取比赛信息。

只输出一个 JSON 对象，不要输出任何其他文字，字段如下：
- is_competition: 布尔。这条通知是否是面向学生的比赛/竞赛/认证考试类通知（需要报名参赛的那种）
- name: 字符串或 null。比赛全名；不是比赛就是 null
- type: 字符串或 null。"deliverable"=交作品的比赛（设计/视频/程序/论文等），"exam"=考试认证类（如 CCF CSP、蓝桥杯程序赛），拿不准就是 null
- deadline: 字符串或 null。报名或提交截止日期，格式 YYYY-MM-DD；原文没写就是 null
- evidence: 字符串。从原文逐字摘抄的、支持你判断的最短句子；不许改写、不许编造
- reason: 字符串。一句话说明判断理由

判定标准：
- 算比赛：学科竞赛、大赛、竞赛报名通知、认证考试报名（CCF CSP、蓝桥杯、数学竞赛等），特征是面向学生征集参赛；
- 不算比赛：成绩/名单/复试结果公示、助教招聘、奖学金评审、学业审核、选课与考试安排、讲座报告、日常行政通知；
- 拿不准时 is_competition 取 false，但 evidence 仍要逐字摘抄让你犹豫的那句原文。
"""

